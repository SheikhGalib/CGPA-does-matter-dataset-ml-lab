"""Assemble the CSE-4112 decks.

Usage:  python build.py [signal|cobalt|swiss|all]

Each deck is a single self-contained HTML file: fonts from Google Fonts, every figure
inlined as a base64 data URI, all CSS and JS inline. No build step for the viewer.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from pres_content import META, OUT, all_figures
from slides_html import render_slides
from deck_shell import BASE_CSS, CHROME_CSS, CHROME_HTML, CONTROLLER_JS

THEMES = {"signal": "theme_signal", "cobalt": "theme_cobalt", "swiss": "theme_swiss"}

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="{fonts}" rel="stylesheet">
<style>
/* ===========================================
   {theme_name} — CSE-4112 Machine Learning Laboratory
   Generated by presentation/build/build.py
   =========================================== */
{base_css}
{chrome_css}
/* ===========================================
   THEME
   =========================================== */
{theme_css}
</style>
</head>
<body>
<div class="deck-viewport">
  <main class="deck-stage" id="deckStage">
{slides}
  </main>
</div>
{chrome_html}
<script>
{js}
</script>
</body>
</html>
"""


def build(key, figs):
    mod = __import__(THEMES[key])
    html = PAGE.format(
        title=f'What Actually Moves a CGPA? — {META["course"]}',
        fonts=mod.FONTS,
        theme_name=mod.NAME,
        base_css=BASE_CSS.strip(),
        chrome_css=CHROME_CSS.strip(),
        theme_css=mod.CSS.strip(),
        slides=render_slides(figs),
        chrome_html=CHROME_HTML.strip(),
        js=(CONTROLLER_JS.replace("__EDITKEY__", f"cse4112-deck-{key}").strip()
            + "\n" + getattr(mod, "EXTRA_JS", "").strip()),
    )
    path = OUT / f"deck-{key}.html"
    path.write_text(html, encoding="utf-8")
    print(f"  {path.name:<22} {len(html)/1024:8.1f} KB   [{mod.NAME}]")
    return path


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    keys = list(THEMES) if which == "all" else [which]
    print("Encoding figures...")
    figs = all_figures()
    print(f"  {len(figs)} figures inlined\n")
    for k in keys:
        try:
            build(k, figs)
        except ModuleNotFoundError:
            print(f"  deck-{k}.html          SKIPPED (theme_{k}.py not written yet)")
