import json,re,csv
from pathlib import Path
E=Path(__file__).resolve().parent.parent/'evidence'
data=json.loads((E/'data.json').read_text(encoding='utf-8'))
def parse(t):
 acc=float(re.search(r'Correctly Classified Instances\s+\d+\s+([\d.]+)',t)[1])
 n=int(re.search(r'Total Number of Instances\s+(\d+)',t)[1])
 cm=[[int(v) for v in re.findall(r'\d+',l.split('|')[0])] for l in t.split('=== Confusion Matrix ===')[1].splitlines() if re.search(r'\|\s+[a-d] =',l)]
 assert sum(map(sum,cm))==n
 assert abs(sum(cm[i][i] for i in range(4))/n*100-acc)<0.0001
 kappa=float(re.search(r'Kappa statistic\s+(-?[\d.]+)',t)[1])
 f1=[2*cm[i][i]/(sum(cm[i])+sum(row[i] for row in cm)) if sum(cm[i])+sum(row[i] for row in cm) else 0 for i in range(4)]
 return dict(acc=acc,n=n,cm=cm,kappa=kappa,macro_f1=sum(f1)/4)
results={}; audit=[]
for key in ['sgpa','questionnaire','main']:
 results[key]={'cv':{}}
 for model in ['J48','RandomForest','SMO','Logistic','NaiveBayes','ZeroR']:
  name=f'{key}_{model}_cv.txt';text=(E/name).read_text();r=parse(text)
  r['source']=name;r['options']=re.search(r'Options: (.*)',text)[1];results[key]['cv'][model]=r
  audit.append([f'32, 42–45 (main); backup',key,model,'10-fold CV, seed 1',r['n'],name,r['options']])
 text=(E/f'{key}_J48_holdout.txt').read_text()
 results[key]['train']=parse(text.split('=== TRAIN ===')[1].split('=== TEST ===')[0])
 results[key]['test']=parse(text.split('=== TEST ===')[1].split('=== ZeroR TEST BASELINE ===')[0])
 results[key]['baseline']=parse(text.split('=== ZeroR TEST BASELINE ===')[1])
 results[key]['tree']=(E/f'{key}_tree.txt').read_text()
 rules=[];stack=[]
 for line in results[key]['tree'].splitlines():
  if not re.match(r'(?:\|   )*\w+ (?:<=|>) ',line):continue
  depth=line.count('|');branch=line.replace('|   ','');cond=branch.split(':')[0]
  stack=stack[:depth]+[cond]
  if ': ' in branch:
   target=re.search(r': (C[0-3])',branch)[1]
   readable=[]
   for cond in stack:
    f,op,num=re.match(r'(\w+) (<=|>) ([\d.]+)',cond).groups();n=int(float(num))
    opts=data['stats'][f]['options']; subset=opts[:n+1] if op=='<=' else opts[n+1:]
    readable.append(data['stats'][f]['label']+': '+(' / '.join(subset)))
   rules.append({'conditions':list(stack),'target':target,'readable':readable})
 results[key]['rules']=rules
 audit.append(['34–41',key,'J48','Fixed supplied train/test split',1102,f'{key}_J48_holdout.txt','-C 0.25 -M 40; train 881 / test 221'])
 audit.append(['36,40',key,'ZeroR','Same supplied train/test split',1102,f'{key}_J48_holdout.txt, ZeroR TEST BASELINE','Fit majority class on train only'])
(E/'results.json').write_text(json.dumps(results,indent=2))
with (E/'slide_result_audit.csv').open('w',newline='',encoding='utf-8') as f:
 w=csv.writer(f);w.writerow(['Slide result','Target','WEKA model','Evaluation','Dataset N','Exact source','Options']);w.writerows(audit)
md='# Slide result audit\n\nAll results below were generated by WEKA 3.8.7 on 13 September 2026.\n\n| Slide result | Target | WEKA model | Evaluation | Dataset N | Exact source | Options |\n|---|---|---|---|---:|---|---|\n'
md+='\n'.join('| '+' | '.join(map(str,r))+' |' for r in audit)
md+='\n\n## Dataset and evaluation scope\n\nDescriptive charts use 1,108 verified clean records. All models use the same 1,102 records after excluding six target-conditioned SGPA imputations. Twelve questionnaire inputs, plus recent SGPA only for main CGPA. No university, department, semester, satisfaction outcome, identifiers, CGPA predictor for SGPA, or synthetic records. CV J48 uses default M=2; explanatory hold-out J48 uses M=40 for readability, specified in advance without selecting on test results. Pre-existing split seed 42, 881/221, CGPA-stratified, reused for every target. Questionnaire mode imputation predates splitting, so scores remain exploratory.\n\nTree images are exports of WEKA TreeVisualizer using the exact J48 graph. Output images render verbatim WEKA logs in a Swing text component; they are not Explorer window screenshots.\n'
(E/'slide_result_audit.md').write_text(md,encoding='utf-8')
print('Verified 18 CV confusion matrices and 9 train/test/baseline matrices. Audit written before deck build.')
